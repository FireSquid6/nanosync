import { mkdir } from "node:fs/promises";
const result = await Bun.build({
  entrypoints: ["packages/admin-ui/src/main.tsx"],
  target: "browser",
  minify: true,
  naming: "admin-[hash].[ext]",
  outdir: "dist/admin",
});
if (!result.success)
  throw new AggregateError(result.logs, "Frontend build failed");
const map: Record<string, { body: string; contentType: string }> = {};
let script = "",
  style = "";
for (const output of result.outputs) {
  const name = output.path.split("/").pop()!;
  if (!/^admin-[a-zA-Z0-9]+\.(js|css)$/.test(name))
    throw new Error("Unexpected frontend artifact " + name);
  const path = "/admin/assets/" + name;
  const css = name.endsWith(".css");
  map[path] = {
    body: await output.text(),
    contentType: css
      ? "text/css; charset=utf-8"
      : "text/javascript; charset=utf-8",
  };
  if (css) style += `<link rel="stylesheet" href="${path}">`;
  else script += `<script type="module" src="${path}"></script>`;
}
map["/admin"] = {
  body: `<!doctype html><!-- Paper UI: https://github.com/FireSquid6/paper-ui @ f6cd7e07c88aa780618717a388c3762fd406bef1; see PAPER-UI-NOTICE.md --><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Nanosync administration</title>${style}</head><body><div id="root"></div>${script}</body></html>`,
  contentType: "text/html; charset=utf-8",
};
await mkdir("packages/admin-ui/generated", { recursive: true });
await Bun.write(
  "packages/admin-ui/generated/assets.ts",
  "// Generated by build/frontend.ts; do not edit.\nexport const adminAssets = " +
    JSON.stringify(map) +
    ";\n",
);
